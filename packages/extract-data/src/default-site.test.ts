test('Prisma: a scalar list with no @default is db, because Prisma Migrate creates a nullable array that a raw insert may omit', async () => {
  // The shape of a real Prisma project: the model says `String[]`, and the migration that
  // Prisma Migrate generated for it adds a nullable column with no default.
  const files: Files = {
    'prisma/schema.prisma': `
      model Webhook {
        id        String   @id @default(cuid())
        url       String
        surveyIds String[]
      }
    `,
    'prisma/migrations/20230101000000_init/migration.sql': `
      -- CreateTable
      CREATE TABLE "Webhook" (
          "id" TEXT NOT NULL,
          "url" TEXT NOT NULL,

          CONSTRAINT "Webhook_pkey" PRIMARY KEY ("id")
      );
    `,
    'prisma/migrations/20230710112555_add_survey_ids_to_webhooks/migration.sql': `
      -- AlterTable
      ALTER TABLE "Webhook" ADD COLUMN     "surveyIds" TEXT[];
    `,
  };
  const out = await extractFiles(files);
  assert.deepEqual(sites(out, 'Webhook'), { id: 'client', url: 'none', surveyIds: 'db' });
  assert.equal(column(out, 'Webhook', 'surveyIds').props['hasDefault'], true);

  // Without the model there is no list default: the same migration alone declares a plain nullable array.
  const migrationOnly = await extractFiles({
    'prisma/migrations/20230710112555_add_survey_ids_to_webhooks/migration.sql': `
      CREATE TABLE "Webhook" ("id" TEXT NOT NULL, "url" TEXT NOT NULL);
      ALTER TABLE "Webhook" ADD COLUMN     "surveyIds" TEXT[];
    `,
  });
  assert.equal(sites(migrationOnly, 'Webhook')['surveyIds'], 'none');
  assert.equal(column(migrationOnly, 'Webhook', 'surveyIds').props['nullable'], true);
});

test('Prisma: a scalar list stays db through DROP DEFAULT, because dropping a default does not make an array column NOT NULL', async () => {
  const model = `
    model Webhook {
      id        String   @id @default(cuid())
      url       String
      surveyIds String[]
    }
  `;
  const create = `
    CREATE TABLE "Webhook" (
        "id" TEXT NOT NULL,
        "url" TEXT NOT NULL,
        "surveyIds" TEXT[] DEFAULT ARRAY[]::TEXT[],

        CONSTRAINT "Webhook_pkey" PRIMARY KEY ("id")
    );
  `;
  // What Prisma Migrate writes when `@default([])` is removed from the list field.
  const dropDefault = 'ALTER TABLE "Webhook" ALTER COLUMN "surveyIds" DROP DEFAULT;';

  const removed = await extractFiles({
    'prisma/schema.prisma': model,
    'prisma/migrations/20230101000000_init/migration.sql': create,
    'prisma/migrations/20230102000000_drop_default/migration.sql': dropDefault,
  });
  assert.deepEqual(sites(removed, 'Webhook'), { id: 'client', url: 'none', surveyIds: 'db' });
  assert.equal(column(removed, 'Webhook', 'surveyIds').props['hasDefault'], true);
  assert.equal(column(removed, 'Webhook', 'surveyIds').props['defaultExpr'], null);

  // A scalar column's default is removed by the same statement: the list rule is not a blanket.
  const scalar = await extractFiles({
    'prisma/schema.prisma': 'model T {\n id Int @id\n note String @default("x")\n}',
    'prisma/migrations/20230101000000_init/migration.sql':
      'CREATE TABLE "T" ("id" INTEGER NOT NULL, "note" TEXT NOT NULL DEFAULT \'x\');',
    'prisma/migrations/20230102000000_drop/migration.sql':
      'ALTER TABLE "T" ALTER COLUMN "note" DROP DEFAULT;',
  });
  assert.equal(sites(scalar, 'T')['note'], 'none');

  // The model keeps `@default([])` while a migration dropped the default (drift): still a nullable array column.
  const drift = await extractFiles({
    'prisma/schema.prisma': model.replace('String[]', 'String[] @default([])'),
    'prisma/migrations/20230101000000_init/migration.sql': create,
    'prisma/migrations/20230102000000_drop_default/migration.sql': dropDefault,
  });
  assert.equal(sites(drift, 'Webhook')['surveyIds'], 'db');
  assert.equal(column(drift, 'Webhook', 'surveyIds').props['hasDefault'], true);

  // The formbricks shape, then a DROP DEFAULT on a column that never had one.
  const added = await extractFiles({
    'prisma/schema.prisma': model,
    'prisma/migrations/20230101000000_init/migration.sql': create.replace(
      ' DEFAULT ARRAY[]::TEXT[]',
      '',
    ),
    'prisma/migrations/20230102000000_drop_default/migration.sql': dropDefault,
  });
  assert.equal(sites(added, 'Webhook')['surveyIds'], 'db');
});

test('Prisma: a scalar list is no longer db once a migration declares the column NOT NULL, and is again when that is lifted', async () => {
  const files = (migration: string): Files => ({
    'prisma/schema.prisma': 'model Webhook {\n id String @id\n surveyIds String[]\n}',
    'prisma/migrations/20230101000000_init/migration.sql': migration,
  });
  const base = 'CREATE TABLE "Webhook" ("id" TEXT NOT NULL, "surveyIds" TEXT[]';

  // The database requires a value for it and nothing supplies one.
  const inline = await extractFiles(files(`${base} NOT NULL);`));
  assert.equal(sites(inline, 'Webhook')['surveyIds'], 'none');
  assert.equal(column(inline, 'Webhook', 'surveyIds').props['hasDefault'], false);
  assert.equal(column(inline, 'Webhook', 'surveyIds').props['nullable'], false);

  const later = await extractFiles({
    ...files(`${base});`),
    'prisma/migrations/20230102000000_require/migration.sql':
      'ALTER TABLE "Webhook" ALTER COLUMN "surveyIds" SET NOT NULL;',
  });
  assert.equal(sites(later, 'Webhook')['surveyIds'], 'none');

  // NOT NULL with a default the migration states is the database's default, as for any column.
  const withDefault = await extractFiles(files(`${base} NOT NULL DEFAULT ARRAY[]::TEXT[]);`));
  assert.equal(sites(withDefault, 'Webhook')['surveyIds'], 'db');

  const lifted = await extractFiles({
    ...files(`${base} NOT NULL);`),
    'prisma/migrations/20230102000000_relax/migration.sql':
      'ALTER TABLE "Webhook" ALTER COLUMN "surveyIds" DROP NOT NULL;',
  });
  assert.equal(sites(lifted, 'Webhook')['surveyIds'], 'db');
});

