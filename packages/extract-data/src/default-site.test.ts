test('an unknown dialect is refused with a diagnostic, never read as the default', async () => {
  for (const dialect of ['sqlite3', 'mysql2', 'pg', 'mssql', '']) {
    const out = await extractFiles(
      { 'db/schema.sql': 'CREATE TABLE lite (id INTEGER PRIMARY KEY, name TEXT);' },
      { dialect },
    );
    assert.equal(out.result.status, 'FAIL', JSON.stringify(dialect));
    assert.deepEqual(
      out.result.diagnostics,
      [
        `invalid option: dialect ${JSON.stringify(dialect)} is not one of clickhouse, mariadb, mysql, postgres, postgresql, sqlite`,
      ],
      JSON.stringify(dialect),
    );
    assert.equal(out.nodes.length, 0, JSON.stringify(dialect));
    assert.equal(out.edges.length, 0, JSON.stringify(dialect));
  }
});

test('every supported dialect value runs, whatever its case, and the sqlite one switches the rowid alias on', async () => {
  const ddl = 'CREATE TABLE lite (id INTEGER PRIMARY KEY, name TEXT);';
  for (const dialect of [
    'postgres',
    'postgresql',
    'PostgreSQL',
    'mysql',
    'mariadb',
    'clickhouse',
  ]) {
    const out = await extractFiles({ 'db/schema.sql': ddl }, { dialect });
    assert.equal(out.result.status, 'PASS', dialect);
  }
  for (const dialect of ['sqlite', 'SQLite']) {
    const out = await extractFiles({ 'db/schema.sql': ddl }, { dialect });
    assert.equal(out.result.status, 'PASS', dialect);
    assert.equal(sites(out, 'lite')['id'], 'db', dialect);
    // The label on the nodes is the canonical lower-case one.
    assert.equal(column(out, 'lite', 'id').props['dialect'], 'sqlite', dialect);
  }
  // Left at the default, the same SQLite file reads as an ordinary key: precision is lost, not recall.
  const unset = await extractFiles({ 'db/schema.sql': ddl });
  assert.equal(sites(unset, 'lite')['id'], 'none');
});

test('a dialect that is not a string is refused like an unknown one, never ignored', async () => {
  const ddl = 'CREATE TABLE lite (id INTEGER PRIMARY KEY, name TEXT);';
  const cases: ReadonlyArray<readonly [unknown, string]> = [
    [['sqlite'], '["sqlite"]'],
    [3, '3'],
    [{ name: 'sqlite' }, '{"name":"sqlite"}'],
    [null, 'null'],
    [true, 'true'],
  ];
  for (const [value, shown] of cases) {
    const out = await extractFiles({ 'db/schema.sql': ddl }, { dialect: value as string });
    assert.equal(out.result.status, 'FAIL', shown);
    assert.deepEqual(
      out.result.diagnostics,
      [
        `invalid option: dialect ${shown} is not one of clickhouse, mariadb, mysql, postgres, postgresql, sqlite`,
      ],
      shown,
    );
    assert.equal(out.nodes.length, 0, shown);
    assert.equal(out.edges.length, 0, shown);
  }
  // An option that is not set at all is the default, not a refusal.
  const unset = await extractFiles(
    { 'db/schema.sql': ddl },
    { dialect: undefined as unknown as string },
  );
  assert.equal(unset.result.status, 'PASS');
});

test('postgresql is stored as postgres, so two spellings of one database give the same nodes; mariadb keeps its own label', async () => {
  const files: Files = {
    'db/schema.sql': 'CREATE TABLE t (id serial PRIMARY KEY, name text NOT NULL);',
    'prisma/schema.prisma': 'model P { id Int @id }',
  };
  const sifOf = (out: ExtractDataOutput): string => canonicalSif(out.nodes, out.edges);
  const reference = sifOf(await extractFiles(files));
  for (const dialect of ['postgres', 'postgresql', 'PostgreSQL', 'POSTGRES']) {
    const out = await extractFiles(files, { dialect });
    assert.equal(sifOf(out), reference, dialect);
  }
  assert.ok(reference.includes('"dialect":"postgres"'));
  assert.ok(!reference.includes('postgresql'));

  // MariaDB is a different database from MySQL: the label is what the caller stated.
  // The rules that depend on the dialect treat the two alike today.
  const maria = await extractFiles(files, { dialect: 'MariaDB' });
  const mysql = await extractFiles(files, { dialect: 'mysql' });
  assert.equal(column(maria, 't', 'id').props['dialect'], 'mariadb');
  assert.equal(column(mysql, 't', 'id').props['dialect'], 'mysql');
  assert.deepEqual(sites(maria, 't'), sites(mysql, 't'));
});

