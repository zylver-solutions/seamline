test('SQL DDL: SQLite INTEGER PRIMARY KEY is a rowid alias, and only that exact shape', async () => {
  const ddl = `
    CREATE TABLE lite_alias (id INTEGER PRIMARY KEY, name TEXT);
    CREATE TABLE lite_auto (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT);
    CREATE TABLE lite_notnull (id INTEGER NOT NULL PRIMARY KEY, name TEXT);
    CREATE TABLE lite_table_pk (id INTEGER, name TEXT, PRIMARY KEY (id));
    CREATE TABLE lite_named_pk (id INTEGER, name TEXT, CONSTRAINT pk PRIMARY KEY (id));
    CREATE TABLE lite_int (id INT PRIMARY KEY, name TEXT);
    CREATE TABLE lite_bigint (id BIGINT PRIMARY KEY, name TEXT);
    CREATE TABLE lite_desc (id INTEGER PRIMARY KEY DESC, name TEXT);
    CREATE TABLE lite_desc_table_pk (id INTEGER, PRIMARY KEY (id DESC));
    CREATE TABLE lite_named_desc_table_pk (id INTEGER, CONSTRAINT pk PRIMARY KEY (id DESC));
    CREATE TABLE lite_desc_norowid (id INTEGER, PRIMARY KEY (id DESC)) WITHOUT ROWID;
    CREATE TABLE lite_norowid (id INTEGER PRIMARY KEY, name TEXT) WITHOUT ROWID;
    CREATE TABLE lite_norowid_table_pk (id INTEGER, name TEXT, PRIMARY KEY (id)) WITHOUT ROWID;
    CREATE TABLE lite_composite (a INTEGER, b INTEGER, PRIMARY KEY (a, b));
    CREATE TABLE lite_explicit (id INTEGER PRIMARY KEY DEFAULT 7, name TEXT);
    CREATE TABLE lite_not_a_key (id INTEGER NOT NULL, name TEXT);
    CREATE TABLE lite_unsigned (id INTEGER UNSIGNED PRIMARY KEY, name TEXT);
    CREATE TABLE lite_unsigned_table_pk (id INTEGER UNSIGNED, name TEXT, PRIMARY KEY (id));
    CREATE TABLE lite_sized (id INTEGER(10) PRIMARY KEY, name TEXT);
    CREATE TABLE lite_lower (id integer primary key, name TEXT);
  `;
  const out = await extractFiles({ 'db/schema.sql': ddl }, { dialect: 'sqlite' });
  const idSite = (table: string): unknown => sites(out, table)['id'];

  assert.equal(idSite('lite_alias'), 'db');
  assert.equal(column(out, 'lite_alias', 'id').props['defaultExpr'], 'rowid');
  assert.equal(idSite('lite_auto'), 'db');
  assert.equal(column(out, 'lite_auto', 'id').props['defaultExpr'], 'autoincrement');
  assert.equal(idSite('lite_notnull'), 'db');
  assert.equal(idSite('lite_table_pk'), 'db');
  assert.equal(idSite('lite_named_pk'), 'db');
  for (const table of ['lite_desc_table_pk', 'lite_named_desc_table_pk']) {
    assert.equal(idSite(table), 'db', table);
    assert.equal(column(out, table, 'id').props['defaultExpr'], 'rowid', table);
    assert.equal(column(out, table, 'id').props['hasDefault'], true, table);
  }
  assert.equal(idSite('lite_explicit'), 'db');
  assert.equal(column(out, 'lite_explicit', 'id').props['defaultExpr'], '7');
  assert.equal(idSite('lite_lower'), 'db');

  for (const table of [
    'lite_int',
    'lite_bigint',
    'lite_desc',
    'lite_desc_norowid',
    'lite_norowid',
    'lite_norowid_table_pk',
    'lite_not_a_key',
    // SQLite reads the declared type `INTEGER UNSIGNED` or `INTEGER(10)`, which is not exactly `INTEGER`.
    'lite_unsigned',
    'lite_unsigned_table_pk',
    'lite_sized',
  ]) {
    assert.equal(idSite(table), 'none', table);
    assert.equal(column(out, table, 'id').props['hasDefault'], false, table);
  }
  assert.deepEqual(sites(out, 'lite_composite'), { a: 'none', b: 'none' });
  // `name` is no key anywhere.
  assert.equal(sites(out, 'lite_alias')['name'], 'none');
});

