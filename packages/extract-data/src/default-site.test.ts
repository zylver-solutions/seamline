/**
 * Where a column's default is supplied (`defaultSite`), one fixture per default
 * form named in design `real-world-inputs.md` section 4.4, and one per
 * combination of sources. Every assertion is an exact prop value on the emitted
 * node, read from a real extraction of files written to a scratch directory.
 */

import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import test from 'node:test';

import type { SeamlineNode } from '@seamline/ontology';
import { canonicalSif } from './emit.ts';
import { extractData, type ExtractDataOptions, type ExtractDataOutput } from './extractor.ts';

type Files = Readonly<Record<string, string>>;

async function extractFiles(
  files: Files,
  extra: Partial<ExtractDataOptions> = {},
): Promise<ExtractDataOutput> {
  const dir = await mkdtemp(join(tmpdir(), 'seamline-default-site-'));
  try {
    for (const [path, text] of Object.entries(files)) {
      await mkdir(dirname(join(dir, path)), { recursive: true });
      await writeFile(join(dir, path), text, 'utf8');
    }
    return await extractData({
      root: dir,
      repo: 'demo',
      runId: 'r1',
      deterministic: true,
      ...extra,
    });
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

function columnsOf(out: ExtractDataOutput, table: string): SeamlineNode[] {
  return out.nodes.filter((n) => n.kind === 'Column' && n.props['table'] === table);
}

/** `column -> defaultSite` for one table, `undefined` where the prop is absent. */
function sites(out: ExtractDataOutput, table: string): Record<string, unknown> {
  const cols = columnsOf(out, table);
  assert.ok(cols.length > 0, `table ${table} has no columns in the output`);
  return Object.fromEntries(cols.map((c) => [c.props['column'], c.props['defaultSite']]));
}

/** `column -> hasDefault`, to pin that `none` is the same statement as `hasDefault: false`. */
function hasDefaults(out: ExtractDataOutput, table: string): Record<string, unknown> {
  return Object.fromEntries(
    columnsOf(out, table).map((c) => [c.props['column'], c.props['hasDefault']]),
  );
}

function column(out: ExtractDataOutput, table: string, name: string): SeamlineNode {
  const found = columnsOf(out, table).find((c) => c.props['column'] === name);
  assert.ok(found !== undefined, `column ${table}.${name} was not extracted`);
  return found;
}

