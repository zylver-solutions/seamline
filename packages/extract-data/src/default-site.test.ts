test('defaultSite is db if any source supplies a database default, client only when every declared default is client-side', async () => {
  const out = await extractFiles({
    'prisma/schema.prisma': `
      model ComboA {
        id      Int      @id
        touched DateTime @updatedAt

        @@map("combo_a")
      }

      model ComboB {
        id      Int      @id
        touched DateTime @updatedAt

        @@map("combo_b")
      }

      model ComboC {
        id      Int      @id
        touched DateTime @updatedAt

        @@map("combo_c")
      }

      model ComboD {
        id    Int      @id
        stamp DateTime @default(now())

        @@map("combo_d")
      }
    `,
    'src/schema.ts': `
      import { pgTable, text } from 'drizzle-orm/pg-core';

      export const comboE = pgTable('combo_e', {
        fn: text('fn').notNull().$defaultFn(() => 'x'),
      });

      export const comboF = pgTable('combo_f', {
        fn: text('fn').notNull().$defaultFn(() => 'x'),
      });
    `,
    'db/combo_f.sql': "ALTER TABLE combo_f ALTER COLUMN fn SET DEFAULT 'y';",
    'prisma/migrations/0001_combo/migration.sql': `
      ALTER TABLE combo_b ALTER COLUMN touched SET DEFAULT now();
      ALTER TABLE combo_c ALTER COLUMN touched DROP DEFAULT;
      ALTER TABLE combo_d ALTER COLUMN stamp DROP DEFAULT;
    `,
  });

  // @updatedAt alone, and .$defaultFn() alone, are client.
  assert.equal(sites(out, 'combo_a')['touched'], 'client');
  assert.equal(sites(out, 'combo_e')['fn'], 'client');
  // @updatedAt in schema.prisma plus a migration DEFAULT now() is db; so is $defaultFn plus a SQL default.
  assert.equal(sites(out, 'combo_b')['touched'], 'db');
  assert.equal(column(out, 'combo_b', 'touched').props['defaultExpr'], 'now()');
  assert.equal(sites(out, 'combo_f')['fn'], 'db');
  // DROP DEFAULT removes the database's default only; the client one is a property of the ORM schema.
  assert.equal(sites(out, 'combo_c')['touched'], 'client');
  assert.equal(column(out, 'combo_c', 'touched').props['hasDefault'], true);
  // ... and with nothing left, the column has no default.
  assert.equal(sites(out, 'combo_d')['stamp'], 'none');
  assert.equal(column(out, 'combo_d', 'stamp').props['hasDefault'], false);
});

// --------------------------------------------------------------------------
// A source that was not read cannot vouch for "client" or "none"
// --------------------------------------------------------------------------

/** A statement beyond the lexer's explicit nesting limit: the data scope fails closed. */
const UNPARSEABLE = `CREATE TABLE broken (${'('.repeat(300_000)}`;

const PRISMA_UPDATED_AT = `
  model Stamped {
    id      Int      @id @default(autoincrement())
    touched DateTime @updatedAt
    plain   String

    @@map("stamped")
  }
`;

test('a source that failed to parse never yields defaultSite client or none by omission', async () => {
  const control = await extractFiles({ 'prisma/schema.prisma': PRISMA_UPDATED_AT });
  assert.equal(control.result.status, 'PASS');
  assert.deepEqual(sites(control, 'stamped'), { id: 'db', touched: 'client', plain: 'none' });

  const failed = await extractFiles({
    'prisma/schema.prisma': PRISMA_UPDATED_AT,
    'prisma/migrations/0001_bad/migration.sql': UNPARSEABLE,
  });
  assert.equal(
    failed.result.status,
    'FAIL',
    'a tokenizer resource limit fails the scope even when another source was read',
  );
  assert.ok(
    failed.result.diagnostics.some((d) =>
      d.startsWith('parse failed for prisma/migrations/0001_bad/migration.sql'),
    ),
  );
  // The migration may have set a database default on `touched`, so `client` is withheld; so is `none`.
  // `hasDefault` keeps saying what was read. A database default that was read stands.
  assert.deepEqual(sites(failed, 'stamped'), { id: 'db', touched: undefined, plain: undefined });
  assert.deepEqual(hasDefaults(failed, 'stamped'), { id: true, touched: true, plain: false });
  assert.ok(!Object.hasOwn(column(failed, 'stamped', 'touched').props, 'defaultSite'));
});

test('a schema source discovery could not read withholds the same facts', async () => {
  const big = `-- ${'x'.repeat(2_000)}\nCREATE TABLE padded (id int);\n`;
  const out = await extractFiles(
    { 'prisma/schema.prisma': PRISMA_UPDATED_AT, 'db/padded.sql': big },
    { maxFileBytes: 1_000 },
  );
  assert.equal(out.result.status, 'PASS');
  assert.ok(out.result.diagnostics.includes('schema source not read (too-large): db/padded.sql'));
  assert.deepEqual(sites(out, 'stamped'), { id: 'db', touched: undefined, plain: undefined });
  // The table that only the skipped file declares does not exist in the output.
  assert.equal(columnsOf(out, 'padded').length, 0);
});

test('with every source read the same props are present, so absence means unread', async () => {
  const out = await extractFiles({ 'prisma/schema.prisma': PRISMA_UPDATED_AT });
  for (const c of columnsOf(out, 'stamped')) {
    assert.ok(Object.hasOwn(c.props, 'defaultSite'), String(c.props['column']));
  }
});

