/** A `pg_dump --schema-only` file for PostgreSQL 10 and later: an identity column is a plain `NOT NULL` one plus an `ALTER`. */
const PG_DUMP = `
--
-- PostgreSQL database dump
--

SET statement_timeout = 0;
SET client_encoding = 'UTF8';
SELECT pg_catalog.set_config('search_path', '', false);

CREATE TABLE public.users (
    id bigint NOT NULL,
    name character varying NOT NULL
);

ALTER TABLE public.users OWNER TO app;

ALTER TABLE public.users ALTER COLUMN id ADD GENERATED ALWAYS AS IDENTITY (
    SEQUENCE NAME public.users_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.users
    ADD CONSTRAINT users_pkey PRIMARY KEY (id);
`;

test('SQL DDL: a pg_dump identity column (ALTER COLUMN ... ADD GENERATED ... AS IDENTITY) is a database default', async () => {
  const out = await extractFiles({ 'db/structure.sql': PG_DUMP });
  assert.deepEqual(sites(out, 'users'), { id: 'db', name: 'none' });
  assert.deepEqual(hasDefaults(out, 'users'), { id: true, name: false });
  // The NOT NULL primary key that nobody supplies is exactly what X5 must not report.
  assert.equal(column(out, 'users', 'id').props['nullable'], false);
  assert.equal(column(out, 'users', 'id').props['isPrimaryKey'], true);

  // The same dump as a migration, and without the sequence options.
  const migrated = await extractFiles({
    'db/migrations/0001_init.sql': PG_DUMP.replace(/\(\s*SEQUENCE[^)]*\)/u, ''),
  });
  assert.deepEqual(sites(migrated, 'users'), { id: 'db', name: 'none' });
});

