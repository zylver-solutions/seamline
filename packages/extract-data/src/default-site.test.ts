test('SQL DDL: MySQL gives the implicit default to the first TIMESTAMP NOT NULL column only', async () => {
  const ddl = `
    CREATE TABLE my_ts_first (id INT, created TIMESTAMP NOT NULL, updated TIMESTAMP NOT NULL);
    CREATE TABLE my_ts_scale (created TIMESTAMP(6) NOT NULL);
    CREATE TABLE my_ts_default (created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated TIMESTAMP NOT NULL);
    CREATE TABLE my_ts_null (created TIMESTAMP NULL, updated TIMESTAMP NOT NULL);
    CREATE TABLE my_ts_onupdate (created TIMESTAMP NOT NULL ON UPDATE CURRENT_TIMESTAMP);
    CREATE TABLE my_ts_nullable (created TIMESTAMP);
    CREATE TABLE my_datetime (created DATETIME NOT NULL);
  `;
  const out = await extractFiles({ 'db/schema.sql': ddl }, { dialect: 'mysql' });
  assert.deepEqual(sites(out, 'my_ts_first'), { id: 'none', created: 'db', updated: 'none' });
  assert.equal(column(out, 'my_ts_first', 'created').props['defaultExpr'], 'current_timestamp');
  assert.equal(column(out, 'my_ts_first', 'created').props['nullable'], false);
  assert.deepEqual(sites(out, 'my_ts_scale'), { created: 'db' });
  // An explicit DEFAULT is the database's own, and the second column gets nothing.
  assert.deepEqual(sites(out, 'my_ts_default'), { created: 'db', updated: 'none' });
  assert.equal(column(out, 'my_ts_default', 'created').props['defaultExpr'], 'CURRENT_TIMESTAMP');
  // A first column declared NULL, or with ON UPDATE, is not given the implicit default, and the
  // columns after it are not "first".
  assert.deepEqual(sites(out, 'my_ts_null'), { created: 'none', updated: 'none' });
  assert.deepEqual(sites(out, 'my_ts_onupdate'), { created: 'none' });
  assert.deepEqual(sites(out, 'my_ts_nullable'), { created: 'none' });
  assert.deepEqual(sites(out, 'my_datetime'), { created: 'none' });

  // The same text under Postgres is a NOT NULL timestamp with no default.
  const pg = await extractFiles({ 'db/schema.sql': ddl });
  assert.deepEqual(sites(pg, 'my_ts_first'), { id: 'none', created: 'none', updated: 'none' });
  assert.equal(column(pg, 'my_ts_first', 'created').props['hasDefault'], false);
});

